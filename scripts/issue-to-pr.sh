
#!/usr/bin/env bash
set -euo pipefail
mkdir -p /tmp/claude-issue-logs
issue_json=$(gh issue view "$ISSUE" --json title,body,author)
author=$(jq -r '.author.login' <<< "$issue_json")
if [[ "$author" != "johnarleyburns" ]]; then
  echo "Refusing to process an issue not authored by repository owner" >&2
  exit 1
fi
branch="claude/issue-${ISSUE}-${GITHUB_RUN_ID}"
git switch -c "$branch"
git config user.name 'github-actions[bot]'
git config user.email '41898282+github-actions[bot]@users.noreply.github.com'
issue_title=$(jq -r '.title' <<< "$issue_json")
issue_body=$(jq -r '.body // ""' <<< "$issue_json")
base_prompt=$(cat <<EOF
Implement GitHub issue #${ISSUE} in ${GITHUB_REPOSITORY}.
Title: ${issue_title}
Description:
${issue_body}

Read CLAUDE.md and current_status.md. Follow their rules. Keep changes narrowly scoped.
Add tests where appropriate. Never use a simulator. Do not run release, signing, or TestFlight tasks.
Do not modify .github/workflows, .github/scripts, secrets, or CI settings.
Do not commit, push, or open PRs; the surrounding automation does those operations.
EOF
)
validation() {
  local attempt="$1"
  local log="/tmp/claude-issue-logs/validation-${attempt}.log"
  set +e
  (
    set -eo pipefail
    swift test --package-path CadenceCore --parallel
    bash scripts/xcodebuild-safe.sh \
      -project Cadence/Cadence.xcodeproj \
      -scheme Cadence \
      -destination 'generic/platform=iOS' \
      CODE_SIGNING_ALLOWED=NO build
    bash scripts/check-test-pyramid.sh
    bash scripts/check-no-network.sh
    bash scripts/check-history-safety.sh
    bash scripts/check-watch-appicon.sh
    bash scripts/check-watch-background-modes.sh
    bash scripts/check-xcodebuild-platform.sh
    bash scripts/check-release-safety.sh
  ) >"$log" 2>&1
  local status=$?
  set -e
  return "$status"
}
passed=false
for attempt in 0 1 2; do
  if [[ "$attempt" == 0 ]]; then
    prompt="$base_prompt"
  else
    prev=$((attempt - 1))
    errors=$(tail -c 14000 "/tmp/claude-issue-logs/validation-${prev}.log")
    prompt="Fix the Swift compilation/test failures from your changes for issue #${ISSUE}. Follow CLAUDE.md. Do not commit or push. Error log excerpt: ${errors}"
  fi
  # Isolated GitHub runner; issue author is allowlisted above. No external PR code is checked out.
  claude -p "$prompt" --permission-mode bypassPermissions --max-turns 35
  if [[ -n "$(git status --porcelain -- .github/workflows .github/scripts)" ]]; then
    echo 'Agent attempted to modify protected automation files' >&2
    exit 1
  fi
  if validation "$attempt"; then
    passed=true
    break
  fi
done
if [[ -z "$(git status --porcelain)" ]]; then
  echo 'No changes produced; leaving issue open without PR.'
  exit 1
fi
# Do not include build outputs, untracked credentials, or generated artifacts.
git add -u
# New Swift/source/test files are permitted; exclude automation and secret-like paths.
while IFS= read -r -d '' file; do
  case "$file" in
    .github/*|*.p12|*.p8|*.mobileprovision|*.env|*.pem|*.key) continue ;;
  esac
  git add -- "$file"
done < <(git ls-files --others --exclude-standard -z)
git diff --cached --quiet && { echo 'No staged code changes'; exit 1; }
git commit -m "Implement issue #${ISSUE} with Claude"
git push --set-upstream origin "$branch"
body=$(printf 'Closes #%s\n\nGenerated by Claude Code.\n\n**macOS validation:** %s (initial run plus at most two repairs).\n\nReview before merging.\n' "$ISSUE" "$([ "$passed" = true ] && echo PASSED || echo FAILED)")
pr_url=$(gh pr create --draft --base main --head "$branch" --title "[Claude] ${issue_title}" --body "$body")
echo "Draft PR: $pr_url"
if [[ "$passed" != true ]]; then
  echo 'Validation failed after two repairs; PR created for human review.' >&2
  exit 1
fi
